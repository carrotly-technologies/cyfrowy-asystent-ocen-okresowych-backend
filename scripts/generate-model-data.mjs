// One-off generator: turns notatki/model-kompetencji.json into a typed TS module
// (src/competency-model/data/model.data.ts), so the app needs no runtime file reads.
//
// Usage: node scripts/generate-model-data.mjs [path/to/model-kompetencji.json]
// Then: npx prettier --write src/competency-model/data/model.data.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const source = resolve(
  process.argv[2] ??
    resolve(import.meta.dirname, '../../notatki/model-kompetencji.json'),
);
const target = resolve(
  import.meta.dirname,
  '../src/competency-model/data/model.data.ts',
);

const raw = JSON.parse(readFileSync(source, 'utf8'));

const model = {
  title: raw.tytul,
  instructions: raw.instrukcje,
  scale: raw.skala.poziomy.map((p) => ({ points: p.punkty, label: p.etykieta })),
  competencies: raw.competencies.map((c) => ({
    id: c.id,
    name: c.competency,
    indicators: c.indicators.map((i) => ({
      id: i.id,
      name: i.name,
      levels: {
        1: i.levels['1'],
        3: i.levels['3'],
        5: i.levels['5'],
        7: i.levels['7'],
        9: i.levels['9'],
      },
    })),
  })),
};

const m = raw.mapowanie_arkuszy;
const periodic = (key) => ({
  appliesTo: m[key].kto,
  mandatoryCriteria: m[key].kryteria_obowiazkowe,
  legalBasis: m[key].podstawa,
});
const sheetMapping = {
  A: periodic('A'),
  B: periodic('B'),
  C: periodic('C'),
  additionalCriteriaNote: m.kryteria_dodatkowe,
  first: {
    elements: m.pierwsza_ocena.elementy,
    legalBasis: m.pierwsza_ocena.podstawa,
    scale: m.pierwsza_ocena.skala_punkty,
  },
};

const out = `// GENERATED by scripts/generate-model-data.mjs from notatki/model-kompetencji.json.
// Do not edit by hand; re-run the script instead. Polish texts are verbatim.
import type { CompetencyModel, SheetMapping } from '../competency-model.types.js';

export const COMPETENCY_MODEL: CompetencyModel = ${JSON.stringify(model, null, 2)};

export const SHEET_MAPPING: SheetMapping = ${JSON.stringify(sheetMapping, null, 2)};
`;

writeFileSync(target, out);
console.log(`Wrote ${target}`);
